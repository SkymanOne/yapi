//! Syntax highlighting: pi's `highlightCode` and `getLanguageFromPath` in
//! `modes/interactive/theme/theme.ts` of pi `v1.0.0`.
//!
//! pi highlights with highlight.js. yapi uses syntect with the syntax
//! definitions in `assets/syntaxes`, which `cargo xtask syntaxes` generates,
//! and gives each TextMate scope the theme color pi gives the matching
//! highlight.js scope. Colors can differ from pi's where the two grammars
//! scope code differently.

use std::sync::LazyLock;

use syntect::easy::ScopeRegionIterator;
use syntect::parsing::{ParseState, Scope, ScopeStack, SyntaxReference, SyntaxSet};

/// A run of highlighted text and how pi's highlight theme draws it: the
/// theme color it names, or `bold`, `italic` or `underline`. `None` is the
/// default color.
pub type Token = (Option<&'static str>, String);

/// Loaded on first use, so runs that highlight nothing never pay for it.
static SYNTAXES: LazyLock<SyntaxSet> = LazyLock::new(|| {
    // Generated by `cargo xtask syntaxes` and decoded by this module's tests.
    syntect::dumps::from_binary(include_bytes!("../assets/syntaxes/syntaxes.packdump"))
});

/// pi's highlight theme (`buildCliHighlightTheme`), keyed by the TextMate
/// scopes that correspond to its highlight.js scopes. The longest prefix of
/// a scope applies.
static STYLES: LazyLock<Vec<(Scope, &'static str)>> = LazyLock::new(|| {
    [
        ("comment", "syntaxComment"),
        ("string", "syntaxString"),
        ("constant.character", "syntaxString"),
        ("constant.numeric", "syntaxNumber"),
        ("constant.language", "syntaxNumber"),
        ("keyword", "syntaxKeyword"),
        ("keyword.operator", "syntaxOperator"),
        ("keyword.operator.word", "syntaxKeyword"),
        ("storage", "syntaxKeyword"),
        ("support.class", "syntaxType"),
        ("support.function", "syntaxType"),
        ("support.macro", "syntaxType"),
        ("support.type", "syntaxType"),
        ("entity.name.class", "syntaxFunction"),
        ("entity.name.enum", "syntaxFunction"),
        ("entity.name.function", "syntaxFunction"),
        ("entity.name.impl", "syntaxFunction"),
        ("entity.name.struct", "syntaxFunction"),
        ("entity.name.trait", "syntaxFunction"),
        ("entity.name.union", "syntaxFunction"),
        ("entity.other.inherited-class", "syntaxFunction"),
        ("entity.name.type", "syntaxType"),
        ("entity.name.tag", "syntaxKeyword"),
        ("entity.other.attribute-name", "syntaxVariable"),
        ("variable.function", "syntaxFunction"),
        ("variable.language", "syntaxVariable"),
        ("variable.parameter", "syntaxVariable"),
        ("variable.other.readwrite.shell", "syntaxVariable"),
        ("meta.annotation", "muted"),
        ("meta.preprocessor", "muted"),
        ("meta.tag", "syntaxPunctuation"),
        ("markup.bold", "bold"),
        ("markup.italic", "italic"),
        ("markup.underline", "underline"),
        ("markup.inserted", "toolDiffAdded"),
        ("markup.deleted", "toolDiffRemoved"),
    ]
    .into_iter()
    .filter_map(|(scope, style)| Some((Scope::new(scope).ok()?, style)))
    .collect()
});

/// Names highlight.js knows that are neither the name nor an extension of
/// the syntax for them.
const ALIASES: &[(&str, &str)] = &[
    ("c#", "C#"),
    ("console", "Bourne Again Shell (bash)"),
    ("csharp", "C#"),
    ("docker", "Dockerfile"),
    ("golang", "Go"),
    ("json5", "JSON"),
    ("jsonc", "JSON"),
    ("jsx", "TypeScriptReact"),
    ("objc", "Objective-C"),
    ("objectivec", "Objective-C"),
    ("plaintext", "Plain Text"),
    ("shell", "Bourne Again Shell (bash)"),
    ("text", "Plain Text"),
];

fn syntax(lang: &str) -> Option<&'static SyntaxReference> {
    let lang = lang.to_ascii_lowercase();
    if lang.is_empty() {
        return None;
    }
    match ALIASES.iter().find(|(alias, _)| *alias == lang) {
        Some((_, name)) => SYNTAXES.find_syntax_by_name(name),
        None => SYNTAXES.find_syntax_by_token(&lang),
    }
}

/// The style of text with scopes `stack`: that of its innermost scope with
/// one.
fn style(stack: &ScopeStack) -> Option<&'static str> {
    stack.as_slice().iter().rev().find_map(|scope| {
        STYLES
            .iter()
            .filter(|(prefix, _)| prefix.is_prefix_of(*scope))
            .max_by_key(|(prefix, _)| prefix.len())
            .map(|(_, style)| *style)
    })
}

/// pi's `highlightCode` for a language it supports: the tokens of each line
/// of `code`. `None` when yapi has no syntax for `lang`, where pi shows the
/// lines in the code block color.
pub fn highlight(code: &str, lang: &str) -> Option<Vec<Vec<Token>>> {
    let syntax = syntax(lang)?;
    let mut state = ParseState::new(syntax);
    let mut stack = ScopeStack::new();
    let mut lines = Vec::new();
    for line in code.split('\n') {
        // The definitions match line ends, so each line is parsed with one.
        let line = format!("{line}\n");
        let ops = state.parse_line(&line, &SYNTAXES).ok()?;
        let mut tokens: Vec<Token> = Vec::new();
        for (text, op) in ScopeRegionIterator::new(&ops, &line) {
            stack.apply(op).ok()?;
            let text = text.strip_suffix('\n').unwrap_or(text);
            if text.is_empty() {
                continue;
            }
            let style = style(&stack);
            match tokens.last_mut() {
                Some((last, run)) if *last == style => run.push_str(text),
                _ => tokens.push((style, text.to_owned())),
            }
        }
        lines.push(tokens);
    }
    Some(lines)
}

/// pi's `getLanguageFromPath`: the highlight.js language of a file, by its
/// extension.
pub fn language_from_path(path: &str) -> Option<&'static str> {
    let extension = path.rsplit('.').next()?.to_ascii_lowercase();
    Some(match extension.as_str() {
        "ts" | "tsx" => "typescript",
        "js" | "jsx" | "mjs" | "cjs" => "javascript",
        "py" => "python",
        "rb" => "ruby",
        "rs" => "rust",
        "go" => "go",
        "java" => "java",
        "kt" => "kotlin",
        "swift" => "swift",
        "c" | "h" => "c",
        "cpp" | "cc" | "cxx" | "hpp" => "cpp",
        "cs" => "csharp",
        "php" => "php",
        "sh" | "bash" | "zsh" => "bash",
        "fish" => "fish",
        "ps1" => "powershell",
        "sql" => "sql",
        "html" | "htm" => "html",
        "css" => "css",
        "scss" => "scss",
        "sass" => "sass",
        "less" => "less",
        "json" => "json",
        "yaml" | "yml" => "yaml",
        "toml" => "toml",
        "xml" => "xml",
        "md" | "markdown" => "markdown",
        "dockerfile" => "dockerfile",
        "makefile" => "makefile",
        "cmake" => "cmake",
        "lua" => "lua",
        "perl" => "perl",
        "r" => "r",
        "scala" => "scala",
        "clj" => "clojure",
        "ex" | "exs" => "elixir",
        "erl" => "erlang",
        "hs" => "haskell",
        "ml" => "ocaml",
        "vim" => "vim",
        "graphql" => "graphql",
        "proto" => "protobuf",
        "tf" | "hcl" => "hcl",
        _ => return None,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn styled(lines: &[Vec<Token>], text: &str) -> Option<&'static str> {
        lines
            .iter()
            .flatten()
            .find(|(_, run)| run == text)
            .and_then(|(style, _)| *style)
    }

    #[test]
    fn languages_by_extension_as_pi() {
        assert_eq!(language_from_path("src/main.rs"), Some("rust"));
        assert_eq!(language_from_path("a/b.test.TSX"), Some("typescript"));
        assert_eq!(language_from_path("Dockerfile"), Some("dockerfile"));
        assert_eq!(language_from_path("notes.txt"), None);
        assert_eq!(language_from_path("Makefile.am"), None);
    }

    #[test]
    fn every_language_pi_names_has_a_syntax() {
        for lang in [
            "typescript",
            "javascript",
            "python",
            "ruby",
            "rust",
            "go",
            "java",
            "kotlin",
            "swift",
            "c",
            "cpp",
            "csharp",
            "php",
            "bash",
            "fish",
            "sql",
            "html",
            "css",
            "scss",
            "sass",
            "less",
            "json",
            "yaml",
            "toml",
            "xml",
            "markdown",
            "dockerfile",
            "makefile",
            "cmake",
            "lua",
            "perl",
            "r",
            "scala",
            "clojure",
            "elixir",
            "erlang",
            "haskell",
            "ocaml",
            "vim",
            "graphql",
            "protobuf",
            "hcl",
            "dart",
            "groovy",
            "nix",
            "diff",
            "tsx",
            "jsx",
            "sh",
            "shell",
            "text",
        ] {
            assert!(syntax(lang).is_some(), "{lang}");
        }
        assert!(syntax("TypeScript").is_some());
        assert!(syntax("").is_none());
        assert!(syntax("no-such-language").is_none());
    }

    #[test]
    fn tokens_keep_the_text_and_carry_pi_theme_colors() {
        let code = "/* a\n b */\nfn main() {\n    let s = \"x\"; // done\n}";
        let lines = highlight(code, "rust").unwrap();
        let text: Vec<String> = lines
            .iter()
            .map(|line| line.iter().map(|(_, run)| run.as_str()).collect())
            .collect();
        assert_eq!(text.join("\n"), code);
        // The comment's state carries to the next line.
        assert_eq!(lines[1], vec![(Some("syntaxComment"), " b */".to_owned())]);
        assert_eq!(styled(&lines, "fn"), Some("syntaxKeyword"));
        assert_eq!(styled(&lines, "main"), Some("syntaxFunction"));
        assert_eq!(styled(&lines, "\"x\""), Some("syntaxString"));
        assert_eq!(styled(&lines, "// done"), Some("syntaxComment"));
        assert_eq!(highlight("x", "no-such-language"), None);
    }

    #[test]
    fn markup_and_diffs() {
        let lines = highlight("**b**", "markdown").unwrap();
        assert_eq!(styled(&lines, "**b**"), Some("bold"));
        let lines = highlight("-old\n+new", "diff").unwrap();
        assert_eq!(lines[0], vec![(Some("toolDiffRemoved"), "-old".to_owned())]);
        assert_eq!(lines[1], vec![(Some("toolDiffAdded"), "+new".to_owned())]);
    }
}
